class tipoData {
    public static void main(String[] args) {
        //DATA TYPES
        int a = 10; //integer
        float f = 3.14f; //float
        double b = 3.14; //double
        char c = 'A'; //character
        char c1 = 65; //character using ASCII code
        String d = "Hello"; //string
        boolean e = true; //boolean
        final float PI = 3.14159f; //constant

        System.out.println("Integer: " + a);
        System.out.println("Float: " + f);
        System.out.println("Double: " + b);
        System.out.println("Character: " + c);
        System.out.println("Character from ASCII: " + c1);
        System.out.println("String: " + d);
        System.out.println("Boolean: " + e);
        System.out.println("Constant PI: " + PI);
    }
}